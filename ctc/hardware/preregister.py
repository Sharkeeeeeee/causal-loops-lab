"""SPDX-License-Identifier: MIT. Fix the predictions and pass criteria before a hardware run.

Writes ctc/hardware/PREREGISTRATION.md and prints its SHA-256. run_ibm.py refuses to submit if
the file is missing or no longer matches what this script generates, and stores the hash with
the results, so the criteria cannot be changed after seeing the data without it showing.

Usage (from the repository root):  python -B ctc/hardware/preregister.py
"""
import hashlib
from pathlib import Path
import sys

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from experiments import BY_NAME, EXPERIMENTS, RULES, exact, fringe, headline_values  # noqa: E402

PATH = HERE / 'PREREGISTRATION.md'
CRITERIA = dict(
    discrimination_min_gap=0.10,   # C1 applies where |PP - P-CTC| (exact) >= this
    discrimination_min_z=5.0,      # C1: measured PP - P-CTC has the predicted sign and |z| >= this
    accuracy_tolerance=0.05,       # C2: every past-preserving headline within this of exact
    eraser_min_visibility=0.85,    # C3: sorted-fringe visibility under past-preserving
    eraser_shift_tolerance=0.15,   # C3: |shift - exact shift| in radians
    eraser_min_z_over_no_loop=5.0,  # C3: (V_PP - V_no_loop) / std
)
NAMES = {'no_loop': 'no loop', 'p_ctc': 'P-CTC', 'past_preserving': 'past-preserving'}


def eraser_exact():
    ex, ey = BY_NAME['eraser_x'], BY_NAME['eraser_y']
    x, y = exact(ex), exact(ey)
    out = {}
    for rule in RULES:
        hx, hy = headline_values(ex, x[rule]), headline_values(ey, y[rule])
        out[rule] = dict(sorted=fringe(hx[2], hy[2]), screen=fringe(hx[1], hy[1]))
    return out


def text():
    c = CRITERIA
    lines = ['# Preregistration: predictions and pass criteria', '',
             'Generated by `ctc/hardware/preregister.py` before the hardware job is submitted. The run',
             'script stores this file\'s SHA-256 with the results. Predictions are exact (numpy), for the',
             'circuits in `ctc/hardware/experiments.py`.', '',
             '## Exact predictions', '',
             '| experiment | quantity | no loop | P-CTC | past-preserving |', '|---|---|---|---|---|']
    for exp in EXPERIMENTS:
        theory = exact(exp)
        values = {rule: headline_values(exp, theory[rule]) for rule in RULES}
        for i, (label, _, _) in enumerate(exp.headlines):
            lines.append(f'| {exp.name} | {label} | ' + ' | '.join(f'{values[r][i]:.4f}' for r in RULES) + ' |')
    lines += ['', '| eraser fringe | no loop | P-CTC | past-preserving |', '|---|---|---|---|']
    ee = eraser_exact()
    for key, name in (('sorted', 'sorted by Bob X = +'), ('screen', 'whole screen')):
        lines.append(f'| visibility, {name} | ' + ' | '.join(f'{ee[r][key][0]:.4f}' for r in RULES) + ' |')
        lines.append(f'| shift (rad), {name} | ' + ' | '.join(
            f'{ee[r][key][1]:.4f}' if ee[r][key][0] > 1e-9 else 'n/a' for r in RULES) + ' |')
    lines += ['', '## Pass criteria', '',
              f'- **C1 (the rules are told apart):** for every quantity where past-preserving and P-CTC differ by at '
              f'least {c["discrimination_min_gap"]} (exact), the measured difference has the predicted sign and '
              f'|z| >= {c["discrimination_min_z"]}, with the standard deviation of the difference from a bootstrap '
              'that resamples both the shots and the readout calibration.',
              f'- **C2 (accuracy):** every past-preserving quantity is within {c["accuracy_tolerance"]} of its exact '
              'value.',
              f'- **C3 (quantum eraser):** under past-preserving, the fringe sorted by Bob X = + has visibility >= '
              f'{c["eraser_min_visibility"]}, its shift is within {c["eraser_shift_tolerance"]} rad of the exact '
              f'value, and its visibility exceeds the no-loop value by z >= {c["eraser_min_z_over_no_loop"]}.',
              '', '## Known limits, stated in advance', '',
              '- All three rules are computed from the same shots. Passing the criteria shows that each rule\'s '
              'predictions can be measured on hardware; it does not show which rule nature uses, or that loops exist.',
              '- Under past-preserving selection, world weights (including Bob\'s own statistics) are taken from all '
              'shots by construction, so they equal the no-loop values. Their agreement with prediction tests the '
              'hardware, not the rule.',
              '- The eraser circuits read Bob in X (eraser_x, eraser_y) or Z (eraser_z). Past-preserving uses Bob\'s '
              'reading as the record, so it uses the X record in the first two and the which-path record in the '
              'third. Which record basis nature would use is the open problem in ctc/PAST_PRESERVING.md; this run '
              'does not decide it.',
              '- "Should be 0" quantities are limited by two-qubit gate errors, which readout correction does not '
              'remove. C2 may fail for them; that outcome will be reported as is.', '']
    return '\n'.join(lines)


def sha256(content):
    return hashlib.sha256(content.encode('utf-8')).hexdigest()


def check():
    """Return the hash of PREREGISTRATION.md if it matches what this script generates, else None."""
    if not PATH.exists():
        return None
    content = PATH.read_text(encoding='utf-8')
    return sha256(content) if content == text() else None


def main():
    content = text()
    PATH.write_text(content, encoding='utf-8', newline='\n')
    print(content)
    print(f'SHA-256 {sha256(content)}  ({PATH})')


if __name__ == '__main__':
    np.set_printoptions(precision=4)
    main()
